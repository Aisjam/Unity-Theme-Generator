using System;
using System.IO;
using System.Text;
using UnityEditor;
using UnityEngine;
using UnityEngine.UIElements;

namespace Aisjam.ThemeGenerator.Editor
{
    internal static class ThemeGeneratorWriter
    {
        internal const string PackageRoot = "Packages/com.aisjam.themegenerator";

        internal static string Generate(ThemeDefinition t, PanelSettings panel, bool applyPanel)
        {
            if (t == null) throw new ArgumentNullException(nameof(t));
            string folder = (t.outputFolder ?? "").Replace('\\', '/').TrimEnd('/');
            if (!(folder == "Assets" || folder.StartsWith("Assets/", StringComparison.Ordinal)) || folder.Contains(".."))
                throw new ArgumentException("Output folder must be inside Assets and cannot contain '..'.");
            Directory.CreateDirectory(folder);
            string template = PackageRoot + "/StyleReferences/" + t.style + ".uss";
            if (!File.Exists(template)) throw new FileNotFoundException("Missing style preset", template);

            File.WriteAllText(folder + "/AisjamTokens.uss", MakeTokens(t), Encoding.UTF8);
            File.WriteAllText(folder + "/AisjamTypography.uss", MakeTypography(t), Encoding.UTF8);
            File.WriteAllText(folder + "/AisjamComponents.uss", File.ReadAllText(template), Encoding.UTF8);
            File.WriteAllText(folder + "/AisjamTheme.tss",
                "@import url(\"unity-theme://default\");\n" +
                "@import url(\"AisjamTokens.uss\");\n" +
                "@import url(\"AisjamTypography.uss\");\n" +
                "@import url(\"AisjamComponents.uss\");\n", Encoding.UTF8);
            AssetDatabase.Refresh();

            if (applyPanel && panel != null)
            {
                ThemeStyleSheet sheet = AssetDatabase.LoadAssetAtPath<ThemeStyleSheet>(folder + "/AisjamTheme.tss");
                if (sheet == null) throw new InvalidOperationException("Unity could not import the generated TSS. Check the Console.");
                Undo.RecordObject(panel, "Apply Aisjam Theme");
                panel.themeStyleSheet = sheet;
                EditorUtility.SetDirty(panel);
                AssetDatabase.SaveAssets();
            }
            return folder + "/AisjamTheme.tss";
        }

        private static string MakeTokens(ThemeDefinition t)
        {
            Color bg = t.baseColour;
            Color surface = ThemeColourRules.Raise(bg, .08f);
            Color elevated = ThemeColourRules.Raise(bg, .16f);
            Color outline = ThemeColourRules.Raise(bg, .32f);
            Color text = ThemeColourRules.ReadableText(bg);
            Color muted = ThemeColourRules.Mix(text, bg, .30f);
            var b = new StringBuilder("/* Generated by Aisjam Theme Generator. Edit ThemeDefinition.asset, not this file. */\n:root {\n");
            void Add(string name, Color c) => b.Append("    --ais-").Append(name).Append(": ").Append(ThemeColourRules.Hex(c)).Append(";\n");
            Add("base", bg); Add("surface", surface); Add("elevated", elevated); Add("outline", outline);
            Add("text", text); Add("text-muted", muted);
            Add("primary", t.primaryColour); Add("primary-hover", ThemeColourRules.Raise(t.primaryColour, .16f));
            Add("primary-pressed", ThemeColourRules.Mix(t.primaryColour, Color.black, .20f));
            Add("on-primary", ThemeColourRules.ReadableText(t.primaryColour));
            Add("accent", t.accentColour); Add("on-accent", ThemeColourRules.ReadableText(t.accentColour));
            Add("actionable", t.actionableColour); Add("on-actionable", ThemeColourRules.ReadableText(t.actionableColour));
            Add("blocked", t.blockedColour); Add("on-blocked", ThemeColourRules.ReadableText(t.blockedColour));
            Add("disabled", ThemeColourRules.Mix(surface, outline, .25f));
            b.Append("}\n");
            return b.ToString();
        }

        private static string MakeTypography(ThemeDefinition t)
        {
            var b = new StringBuilder("/* Generated typography. Fonts are optional. */\n");
            AppendFont(b, ".ais-heading, .ais-title", t.headingFont, "font-size: 24px; -unity-font-style: bold;");
            AppendFont(b, ".ais-body, .ais-label, .ais-button, .ais-input", t.bodyFont, "font-size: 14px;");
            b.Append(".ais-caption { font-size: 11px; color: var(--ais-text-muted); }\n");
            return b.ToString();
        }

        private static void AppendFont(StringBuilder b, string selectors, Font font, string extra)
        {
            b.Append(selectors).Append(" { ").Append(extra);
            if (font != null)
            {
                string path = AssetDatabase.GetAssetPath(font);
                if (!string.IsNullOrEmpty(path))
                    b.Append(" -unity-font-definition: url(\"project://database/").Append(path.Replace("\\", "/")).Append("\");");
            }
            b.Append(" }\n");
        }
    }
}
